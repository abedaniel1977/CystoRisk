export function makeT(lang) {
  const d = STRINGS[lang] || STRINGS.pt;
  return (key, vars = {}) => {
    let s = d[key] ?? STRINGS.pt[key] ?? key;
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
  };
}
